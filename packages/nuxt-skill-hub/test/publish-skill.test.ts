import { execSync } from 'node:child_process'
import { promises as fsp } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { publishSkill } from '../src/generator'

let root: string
let generatedSkillRoot: string
const logger = { start: vi.fn(), success: vi.fn(), warn: vi.fn(), info: vi.fn() }

beforeEach(async () => {
  root = await fsp.mkdtemp(join(tmpdir(), 'skill-hub-publish-'))
  execSync('git init -q', { cwd: root })
  generatedSkillRoot = join(root, 'node_modules/.cache/nuxt-skill-hub/generated/nuxt-app')
  await fsp.mkdir(join(generatedSkillRoot, 'references/nuxt/rules'), { recursive: true })
  await fsp.writeFile(join(generatedSkillRoot, 'SKILL.md'), '# Nuxt Skill Router\n\n_Generated by nuxt-skill-hub. Do not edit this file manually._\n')
  await fsp.writeFile(join(generatedSkillRoot, 'references/nuxt/rules/plugins.md'), '## Plugins and Runtime Boot\n')
  await fsp.writeFile(join(generatedSkillRoot, '.gitignore'), '# generated\n*\n')
  await fsp.writeFile(join(root, '.gitignore'), 'node_modules\n')
  vi.clearAllMocks()
})

afterEach(async () => {
  await fsp.rm(root, { recursive: true, force: true })
})

function publish(targets: string[]) {
  return publishSkill({ logger, rootDir: root, exportRoot: root, skillName: 'nuxt-app', targets, generatedSkillRoot })
}

describe('publishSkill', () => {
  it('copies the whole tree for skill-folder agents and keeps it out of git', async () => {
    await publish(['claude-code'])

    const skillRoot = join(root, '.claude/skills/nuxt-app')
    await expect(fsp.readFile(join(skillRoot, 'SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    await expect(fsp.readFile(join(skillRoot, 'references/nuxt/rules/plugins.md'), 'utf8')).resolves.toContain('Plugins')
    expect(execSync('git status --porcelain', { cwd: root, encoding: 'utf8' }).trim()).toBe('?? .gitignore')
  })

  it('leaves an up-to-date copy in place and replaces it after a new generation', async () => {
    const writeState = (generatedAt: string) => fsp.writeFile(
      join(generatedSkillRoot, '.state.json'),
      JSON.stringify({ fingerprint: 'abc', generatedAt, packageVersion: '0.0.0' }),
    )
    const skillRoot = join(root, '.claude/skills/nuxt-app')
    await writeState('2026-01-01T00:00:00.000Z')
    await publish(['claude-code'])
    await fsp.writeFile(join(skillRoot, 'marker'), '')

    await publish(['claude-code'])
    await expect(fsp.access(join(skillRoot, 'marker'))).resolves.toBeUndefined()

    await writeState('2026-01-02T00:00:00.000Z')
    await publish(['claude-code'])
    await expect(fsp.access(join(skillRoot, 'marker'))).rejects.toBeDefined()
  })

  it('writes one pointer file for agents that load a rules directory', async () => {
    await publish(['windsurf'])

    const pointerRoot = join(root, '.codeium/windsurf/rules/nuxt-app')
    expect(await fsp.readdir(pointerRoot)).toEqual(['SKILL.md'])
    const pointer = await fsp.readFile(join(pointerRoot, 'SKILL.md'), 'utf8')
    expect(pointer).toContain('[the generated Nuxt skill](../../../../node_modules/.cache/nuxt-skill-hub/generated/nuxt-app/SKILL.md)')
    expect(pointer).toContain('run `npx nuxt prepare` from the repository root')
  })

  it('replaces a wrapper from an older version but leaves a hand-written skill alone', async () => {
    const claudeRoot = join(root, '.claude/skills/nuxt-app')
    await fsp.mkdir(claudeRoot, { recursive: true })
    await fsp.writeFile(join(claudeRoot, 'SKILL.md'), '# Nuxt Skill Wrapper\n')
    const agentsRoot = join(root, '.agents/skills/nuxt-app')
    await fsp.mkdir(agentsRoot, { recursive: true })
    await fsp.writeFile(join(agentsRoot, 'SKILL.md'), '# My own Nuxt notes\n')

    await publish(['claude-code', 'codex'])

    await expect(fsp.readFile(join(claudeRoot, 'SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    await expect(fsp.readFile(join(agentsRoot, 'SKILL.md'), 'utf8')).resolves.toBe('# My own Nuxt notes\n')
    expect(logger.warn).toHaveBeenCalledWith(expect.stringContaining(`Skipped ${agentsRoot}`))
  })

  it('writes once when two agents share a skills dir through a symlink', async () => {
    await fsp.mkdir(join(root, '.agents/skills'), { recursive: true })
    await fsp.mkdir(join(root, '.claude'), { recursive: true })
    await fsp.symlink('../.agents/skills', join(root, '.claude/skills'))

    await publish(['codex', 'claude-code'])

    expect((await fsp.readdir(join(root, '.agents/skills'))).sort()).toEqual(['nuxt-app'])
    await expect(fsp.readFile(join(root, '.claude/skills/nuxt-app/SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    expect(logger.warn).not.toHaveBeenCalled()
  })

  it('writes one copy to .agents/skills for the agents that read it', async () => {
    await publish(['amp', 'cline', 'codex', 'cursor', 'universal'])

    await expect(fsp.readFile(join(root, '.agents/skills/nuxt-app/references/nuxt/rules/plugins.md'), 'utf8')).resolves.toContain('Plugins')
    expect((await fsp.readdir(root)).filter(name => ['.amp', '.cline', '.codex', '.cursor'].includes(name))).toEqual([])
    expect(execSync('git status --porcelain', { cwd: root, encoding: 'utf8' }).trim()).toBe('?? .gitignore')
  })

  it('removes the copies older versions wrote to the agent folders, but not hand-written skills', async () => {
    const oldCodexRoot = join(root, '.codex/skills/nuxt-app')
    await fsp.mkdir(oldCodexRoot, { recursive: true })
    await fsp.writeFile(join(oldCodexRoot, 'SKILL.md'), '# Nuxt Skill Router\n\n_Generated by nuxt-skill-hub. Do not edit this file manually._\n')
    const oldCursorRoot = join(root, '.cursor/rules/nuxt-app')
    await fsp.mkdir(oldCursorRoot, { recursive: true })
    await fsp.writeFile(join(oldCursorRoot, 'SKILL.md'), '# My own Nuxt rules\n')

    await publish(['codex', 'cursor'])

    await expect(fsp.readFile(join(root, '.agents/skills/nuxt-app/SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    expect(await fsp.readdir(join(root, '.codex/skills'))).toEqual([])
    await expect(fsp.readFile(join(oldCursorRoot, 'SKILL.md'), 'utf8')).resolves.toBe('# My own Nuxt rules\n')
  })

  it('removes the copies older versions wrote for the agents the universal target covers', async () => {
    const oldCodexRoot = join(root, '.codex/skills/nuxt-app')
    await fsp.mkdir(oldCodexRoot, { recursive: true })
    await fsp.writeFile(join(oldCodexRoot, 'SKILL.md'), '# Nuxt Skill Router\n\n_Generated by nuxt-skill-hub. Do not edit this file manually._\n')

    await publish(['universal'])

    await expect(fsp.readFile(join(root, '.agents/skills/nuxt-app/SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    expect(await fsp.readdir(join(root, '.codex/skills'))).toEqual([])
  })

  it('keeps the old copy when .agents/skills holds a hand-written skill of the same name', async () => {
    const oldCodexRoot = join(root, '.codex/skills/nuxt-app')
    await fsp.mkdir(oldCodexRoot, { recursive: true })
    await fsp.writeFile(join(oldCodexRoot, 'SKILL.md'), '# Nuxt Skill Router\n\n_Generated by nuxt-skill-hub. Do not edit this file manually._\n')
    await fsp.mkdir(join(root, '.agents/skills/nuxt-app'), { recursive: true })
    await fsp.writeFile(join(root, '.agents/skills/nuxt-app/SKILL.md'), '# My own Nuxt notes\n')

    await publish(['codex'])

    await expect(fsp.readFile(join(oldCodexRoot, 'SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
  })

  it('keeps the new copy when an old agent folder links to .agents/skills', async () => {
    await fsp.mkdir(join(root, '.agents/skills'), { recursive: true })
    await fsp.mkdir(join(root, '.codex'), { recursive: true })
    await fsp.symlink('../.agents/skills', join(root, '.codex/skills'))

    await publish(['codex'])

    await expect(fsp.readFile(join(root, '.agents/skills/nuxt-app/SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
  })
})
